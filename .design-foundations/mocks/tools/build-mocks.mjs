#!/usr/bin/env node
// build-mocks.mjs: the Phase 7 renders (kiwi-ui/DESIGN.md + kiwi-ui/JOURNEY.md → .design-foundations/mocks/screens/).
// Twelve static files, one per screen and colour mode: the generated token CSS pasted verbatim as the first <style>
// (so every colour on the page is a token), mock.css second, fonts and the Phase 4 drawings as sibling files under
// mocks/assets/, no script. The words come from the revision index by id (lib/copy.mjs); the run writes the strings
// manifest the audit reads back (tools/generated/strings-manifest.json). Nothing here is machine-specific.
//   node build-mocks.mjs            (then node shoot-mocks.mjs for the screenshots and the audit)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { SCREENS as OUTDIR, TOKENS_CSS, TOOLS, rel } from "./lib/paths.mjs";
import { SCREENS } from "./lib/screens.mjs";
import { resetIds } from "./lib/ui.mjs";
import { manifestJson } from "./lib/copy.mjs";

export const tokensCss = () => readFileSync(TOKENS_CSS, "utf8").trimEnd();
export const tokensHash = (css) => createHash("sha256").update(css).digest("hex").slice(0, 16);
export const mockCss = () => readFileSync(join(TOOLS, "mock.css"), "utf8").trimEnd();

export function documentHtml({ title, theme, head = "", body, css, hash, fonts = [], description }) {
  return `<!DOCTYPE html>
<html lang="en" data-theme="${theme}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${title}</title>
<meta name="description" content="${description}">
<!-- Kiwi UI Stage 1, Phase 7 final mock (plan .design-foundations/plans/2026-10-16-kiwi-ui-stage-1.md). Generated by
     .design-foundations/mocks/tools/build-mocks.mjs from kiwi-ui/DESIGN.md (the generated tokens, below, verbatim) and the page
     specs of kiwi-ui/JOURNEY.md; every interface string comes from the Phase 5 revision index by id. Self-contained: no network,
     no script; fonts and the Phase 4 drawings are sibling files under ../assets/. Do not edit: re-run the generator. -->
<link rel="stylesheet" href="../assets/fonts/source-sans-3.css">
${fonts.map((f) => `<link rel="stylesheet" href="../assets/fonts/${f}">`).join("\n")}
<style id="tokens">
/* GENERATED: .design-foundations/tokens/generated/kiwi-ui.tokens.css (sha256 ${hash}), pasted verbatim by build-mocks.mjs. Do not edit. */
${css.tokens}
</style>
<style id="mock">
${css.mock}
</style>${head}
</head>
<body>
${body}
</body>
</html>
`;
}

export function buildGated() {
  const tokens = tokensCss(); const hash = tokensHash(tokens); const mock = mockCss();
  mkdirSync(OUTDIR, { recursive: true });
  const written = [];
  for (const s of SCREENS) {
    for (const theme of ["light", "dark"]) {
      resetIds();
      const ctx = { theme, mode: "gated", url: (p) => `../assets/${p}` };
      const body = s.build(ctx);
      const html = documentHtml({
        title: `${s.name} · Kiwi UI Stage 1 mock (${theme})`,
        description: `Phase 7 final mock of ${s.spec} in ${theme} mode, from kiwi-ui/DESIGN.md and kiwi-ui/JOURNEY.md.`,
        theme, body, css: { tokens, mock }, hash, fonts: s.fonts || [],
      });
      const file = join(OUTDIR, `${s.key}.${theme}.html`);
      writeFileSync(file, html);
      written.push(rel(file));
    }
  }
  mkdirSync(join(TOOLS, "generated"), { recursive: true });
  writeFileSync(join(TOOLS, "generated", "strings-manifest.json"), JSON.stringify({ tokens: hash, strings: manifestJson() }, null, 1) + "\n");
  return { written, hash };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { written, hash } = buildGated();
  console.log(`tokens sha256 ${hash}`);
  for (const f of written) console.log("wrote", f);
}
