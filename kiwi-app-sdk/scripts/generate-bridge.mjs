#!/usr/bin/env node
/**
 * generate-bridge — emit the bridge op layer from the Kiwi backend's OpenAPI.
 *
 * The backend marks each App API endpoint that frontend-only apps may invoke
 * with `@BridgeOp({...})`, which surfaces as an `x-kiwi-bridge-op` extension on
 * the operation in /docs-json. Everything else we need — HTTP method, path,
 * operationId, param and response schemas — is already in the spec, and is the
 * same document kiwi-ui generates its typed client from.
 *
 * From that single source we emit:
 *   --sdk-out   <dir>  src/ops.generated.ts     (SDK: op metadata + param/result types)
 *   --host-out  <dir>  bridgeOps.generated.ts   (kiwi-ui: proxy dispatch table)
 *   --docs-out  <file> BRIDGE-OPS.md            (developer reference)
 *
 * so op params, response types and required scopes cannot drift from the real
 * endpoints.
 *
 *   node scripts/generate-bridge.mjs --spec http://localhost:3000/docs-json \
 *     --sdk-out src --host-out ../kiwi-ui/src/apps/classApps --docs-out BRIDGE-OPS.md
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';

const EXT = 'x-kiwi-bridge-op';
const BANNER = '// AUTO-GENERATED by scripts/generate-bridge.mjs — do not edit by hand.\n' +
  '// Regenerate: npm run generate-bridge (requires the Kiwi backend running).\n';

// ---------------------------------------------------------------- args
function parseArgs(argv) {
  const out = { spec: 'http://localhost:3000/docs-json' };
  for (let i = 2; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) out[a.slice(2)] = argv[i + 1]?.startsWith('--') ? true : argv[++i];
  }
  return out;
}

async function loadSpec(spec) {
  if (/^https?:/.test(spec)) {
    const res = await fetch(spec);
    if (!res.ok) throw new Error(`could not fetch ${spec}: HTTP ${res.status}`);
    return res.json();
  }
  return JSON.parse(readFileSync(spec, 'utf8'));
}

// ---------------------------------------------------------------- helpers
const camel = (s) => s.charAt(0).toLowerCase() + s.slice(1);
/** NestJS operationId "AppDataController_getDocumentChunks" -> generated client
 *  method "appDataControllerGetDocumentChunks" (matches openapi-generator). */
const clientMethodName = (operationId) =>
  camel(operationId.replace(/_(.)/g, (_, c) => c.toUpperCase()));
const refName = (ref) => ref.split('/').pop();

const warnings = [];

/** Minimal, explicit schema -> TS. Anything it doesn't understand becomes
 *  `unknown` AND is reported, so gaps are visible instead of silently `any`. */
function tsType(schema, spec, seen) {
  if (!schema) return 'unknown';
  if (schema.$ref) { collectSchema(refName(schema.$ref), spec, seen); return refName(schema.$ref); }
  const nullable = schema.nullable ? ' | null' : '';
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ') + nullable;
  switch (schema.type) {
    case 'string': return 'string' + nullable;
    case 'number': case 'integer': return 'number' + nullable;
    case 'boolean': return 'boolean' + nullable;
    case 'array': {
      // Parenthesise unions: `A | B[]` parses as `A | (B[])`, which would type
      // an array-of-enum as "two strings or an array of the third".
      const item = tsType(schema.items, spec, seen);
      return `${/[|&]/.test(item) ? `(${item})` : item}[]${nullable}`;
    }
    case 'object':
      if (schema.properties) return inlineObject(schema, spec, seen) + nullable;
      return 'Record<string, unknown>' + nullable;
    default:
      if (schema.properties) return inlineObject(schema, spec, seen) + nullable;
      warnings.push(`unsupported schema (type=${schema.type ?? 'none'}) -> unknown`);
      return 'unknown';
  }
}

function inlineObject(schema, spec, seen) {
  const req = new Set(schema.required ?? []);
  const fields = Object.entries(schema.properties ?? {}).map(
    ([k, v]) => `    ${k}${req.has(k) ? '' : '?'}: ${tsType(v, spec, seen)};`,
  );
  return `{\n${fields.join('\n')}\n  }`;
}

/** Emit a named interface for a component schema (recursively). */
function collectSchema(name, spec, seen) {
  if (seen.has(name)) return;
  const schema = spec.components?.schemas?.[name];
  if (!schema) { warnings.push(`missing component schema: ${name}`); return; }
  seen.set(name, null); // reserve (cycle guard)
  const req = new Set(schema.required ?? []);
  const doc = schema.description ? `/** ${schema.description} */\n` : '';
  const fields = Object.entries(schema.properties ?? {}).map(([k, v]) => {
    const d = v.description ? `  /** ${v.description.replace(/\s+/g, ' ')} */\n` : '';
    return `${d}  ${k}${req.has(k) ? '' : '?'}: ${tsType(v, spec, seen)};`;
  });
  seen.set(name, `${doc}export interface ${name} {\n${fields.join('\n')}\n}`);
}

// ---------------------------------------------------------------- collect ops
function collectOps(spec) {
  const ops = [];
  // The keys an app may send. Computed once here so every emitter (SDK meta,
  // docs table) reads the same list instead of recomputing it.
  const appParamsFor = (bodySchema, appQuery) =>
    bodySchema
      ? Object.keys(spec.components?.schemas?.[bodySchema]?.properties ?? {})
      : appQuery.map((p) => p.name);
  for (const [path, methods] of Object.entries(spec.paths ?? {})) {
    for (const [method, operation] of Object.entries(methods)) {
      const meta = operation?.[EXT];
      if (!meta) continue;

      const injected = meta.injectedParams ?? {};
      const params = operation.parameters ?? [];
      const appQuery = params.filter((p) => !(p.name in injected)).map((p) => ({
        name: p.name, in: p.in, schema: p.schema, required: !!p.required, description: p.description,
      }));
      const pathParams = params.filter((p) => p.in === 'path').map((p) => p.name);

      // POST body: the DTO *is* the app-supplied params.
      const bodyRef = operation.requestBody?.content?.['application/json']?.schema?.$ref;
      const bodySchema = bodyRef ? refName(bodyRef) : null;
      const bodyParamName = bodySchema ? camel(bodySchema) : null;

      const okResponse = operation.responses?.['200'] ?? operation.responses?.['201'];
      const resultRef = okResponse?.content?.['application/json']?.schema?.$ref;

      ops.push({
        op: meta.op,
        method: method.toUpperCase(),
        path,
        operationId: operation.operationId,
        clientMethod: clientMethodName(operation.operationId),
        summary: operation.summary ?? '',
        requiredScopes: meta.requiredScopes ?? [],
        dynamicScopes: meta.dynamicScopes ?? [],
        injectedParams: injected,
        timeoutMs: meta.timeoutMs ?? 30000,
        appTokenOnly: !!meta.appTokenOnly,
        pathParams,
        appQuery,
        appParams: appParamsFor(bodySchema, appQuery),
        bodySchema,
        bodyParamName,
        resultSchema: resultRef ? refName(resultRef) : null,
      });
    }
  }
  ops.sort((a, b) => a.op.localeCompare(b.op));
  return ops;
}

// ---------------------------------------------------------------- SDK emit
function emitSdk(ops, spec) {
  const seen = new Map();
  const paramTypeFor = (o) => {
    if (o.bodySchema) { collectSchema(o.bodySchema, spec, seen); return o.bodySchema; }
    // GET: synthesize a params interface from the app-supplied query params.
    const name = `${o.op.charAt(0).toUpperCase()}${o.op.slice(1)}Params`;
    const fields = o.appQuery.map((p) => {
      const d = p.description ? `  /** ${p.description.replace(/\s+/g, ' ')} */\n` : '';
      return `${d}  ${p.name}${p.required ? '' : '?'}: ${tsType(p.schema, spec, seen)};`;
    });
    seen.set(name, `export interface ${name} {\n${fields.join('\n')}\n}`);
    return name;
  };

  const rows = ops.map((o) => {
    const paramType = paramTypeFor(o);
    if (o.resultSchema) collectSchema(o.resultSchema, spec, seen);
    return { ...o, paramType, resultType: o.resultSchema ?? 'unknown' };
  });

  const interfaces = [...seen.values()].filter(Boolean).join('\n\n');

  const metaEntries = rows.map((o) => `  ${o.op}: {
    op: '${o.op}',
    method: '${o.method}',
    path: '${o.path}',
    operationId: '${o.operationId}',
    clientMethod: '${o.clientMethod}',
    requiredScopes: ${JSON.stringify(o.requiredScopes)},
    dynamicScopes: ${JSON.stringify(o.dynamicScopes)},
    injectedParams: ${JSON.stringify(o.injectedParams)},
    appParams: ${JSON.stringify(o.appParams)},
    timeoutMs: ${o.timeoutMs},
    appTokenOnly: ${o.appTokenOnly},
  },`).join('\n');

  const opsMap = rows.map((o) => `  ${o.op}: { params: ${o.paramType}; result: ${o.resultType} };`).join('\n');

  return `${BANNER}
// ---------------------------------------------------------------------------
// Schemas (from the backend's OpenAPI components)
// ---------------------------------------------------------------------------

${interfaces}

// ---------------------------------------------------------------------------
// Bridge ops
// ---------------------------------------------------------------------------

export interface BridgeOpMeta {
  op: string;
  method: string;
  path: string;
  operationId: string;
  /** Method name on the generated typed client. */
  clientMethod: string;
  /** Scopes the app token must carry (host pre-flight; backend still enforces). */
  requiredScopes: string[];
  /** Scopes templated from params, e.g. llm:prompt:{promptId} — backend-only. */
  dynamicScopes: string[];
  /** OpenAPI param name -> host-context key. Supplied by the host, never the app. */
  injectedParams: Record<string, string>;
  /** Keys the app may send. */
  appParams: string[];
  timeoutMs: number;
  appTokenOnly: boolean;
}

export const BRIDGE_OPS = {
${metaEntries}
} as const satisfies Record<string, BridgeOpMeta>;

export type OpName = keyof typeof BRIDGE_OPS;

/** Op name -> its params and result types. */
export interface KiwiOps {
${opsMap}
}
`;
}

// ---------------------------------------------------------------- host emit
function emitHost(ops) {
  const entries = ops.map((o) => {
    const injectedArgs = Object.entries(o.injectedParams)
      .map(([param, key]) => `${param}: inj.${key}`);
    let args;
    if (o.bodySchema) {
      args = `{ ${injectedArgs.join(', ')}${injectedArgs.length ? ', ' : ''}${o.bodyParamName}: p as never }`;
    } else {
      const query = o.appQuery.map((p) => `${p.name}: p.${p.name} as never`);
      args = `{ ${[...injectedArgs, ...query].join(', ')} }`;
    }
    return `  ${o.op}: {
    requiredScopes: ${JSON.stringify(o.requiredScopes)},
    dynamicScopes: ${JSON.stringify(o.dynamicScopes)},
    timeoutMs: ${o.timeoutMs},
    invoke: (p, inj, io) =>
      bridgeKiwiAppsApiClient.${o.clientMethod}(${args}, io as never),
  },`;
  }).join('\n');

  return `${BANNER}/**
 * Proxy dispatch table for kiwi:apiRequest. Maps each bridge op to its typed
 * KiwiAppsApi method on the middleware-free bridge client (the host injects the
 * app token per call). classId/appSlug come from trusted host context — never
 * from the app — so an app cannot address another class or app.
 */
import { bridgeKiwiAppsApiClient } from '../../utils/api.ts';

export interface BridgeOpDef {
  requiredScopes: string[];
  /** Scopes templated from app params, e.g. \`llm:prompt:{promptId}\`. */
  dynamicScopes: string[];
  timeoutMs: number;
  invoke: (
    params: Record<string, unknown>,
    injected: { classId: string; appSlug: string },
    initOverride: unknown,
  ) => Promise<unknown>;
}

export const OP_TABLE: Record<string, BridgeOpDef> = {
${entries}
};

/**
 * Every scope this call needs: the static ones plus each dynamic template
 * resolved against the app-supplied params (\`llm:prompt:{promptId}\` with
 * \`{promptId: 'weekly-summary'}\` -> \`llm:prompt:weekly-summary\`).
 *
 * Without this the pre-flight would pass on a token that the backend then
 * rejects with a 403 — a wasted round-trip and a misleading error naming only
 * the static scopes. A template whose param is missing is dropped rather than
 * checked literally; the backend is still the enforcement point.
 */
export function requiredScopesFor(
  def: BridgeOpDef,
  params: Record<string, unknown>,
): string[] {
  const resolved: string[] = [];
  for (const tpl of def.dynamicScopes) {
    let missing = false;
    const scope = tpl.replace(/\\{(\\w+)\\}/g, (_m, key) => {
      const v = params?.[key];
      if (typeof v !== 'string' && typeof v !== 'number') {
        missing = true;
        return '';
      }
      return String(v);
    });
    if (!missing) resolved.push(scope);
  }
  return [...def.requiredScopes, ...resolved];
}

/** Wildcard-aware scope match, mirroring the backend scope-check util. */
export function scopeMatches(granted: string[], required: string[]): boolean {
  return required.every((need) =>
    granted.some(
      (s) => s === need || (s.endsWith(':*') && need.startsWith(s.slice(0, -1))),
    ),
  );
}
`;
}

// ---------------------------------------------------------------- docs emit
function emitDocs(ops) {
  const rows = ops.map((o) => {
    const scopes = [...o.requiredScopes, ...o.dynamicScopes].map((s) => `\`${s}\``).join(' + ') || '—';
    return `| \`${o.op}\` | \`${o.method} ${o.path}\` | ${scopes} | ${o.appParams?.join(', ') || ''} |`;
  });
  const detail = ops.map((o) => {
    const injected = Object.entries(o.injectedParams)
      .map(([p, k]) => `\`${p}\` (from ${k})`).join(', ') || 'none';
    return `### \`${o.op}\`

${o.summary}

- **Endpoint:** \`${o.method} ${o.path}\`
- **Scopes:** ${[...o.requiredScopes, ...o.dynamicScopes].map((s) => `\`${s}\``).join(' + ') || '—'}
- **Host-injected params:** ${injected} — the app cannot set these.
- **App-token only:** ${o.appTokenOnly ? 'yes' : 'no'}
- **Timeout:** ${o.timeoutMs} ms
- **SDK:** \`await kiwi.${o.op}({ … })\``;
  }).join('\n\n');

  return `${'<!-- AUTO-GENERATED by scripts/generate-bridge.mjs — do not edit by hand. -->'}

# Bridge ops

Ops a frontend-only Kiwi App can invoke through the window proxy
(\`kiwi:apiRequest\`). The host makes the real call with the app token, so your
app needs no token and no CORS entry.

| Op | Endpoint | Scopes | App params |
| --- | --- | --- | --- |
${rows.join('\n')}

${detail}
`;
}

// ---------------------------------------------------------------- main
const args = parseArgs(process.argv);
const spec = await loadSpec(args.spec);
const ops = collectOps(spec);

if (!ops.length) {
  console.error(`No operations carry "${EXT}". Is the backend running the branch with @BridgeOp()?`);
  process.exit(1);
}

const write = (file, contents) => {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, contents);
  console.log(`  wrote ${file}`);
};

console.log(`generate-bridge: ${ops.length} op(s) from ${args.spec}`);
for (const o of ops) console.log(`  - ${o.op}  ${o.method} ${o.path}  [${o.requiredScopes.join(', ') || 'no scopes'}]`);

if (args['sdk-out']) write(join(args['sdk-out'], 'ops.generated.ts'), emitSdk(ops, spec));
if (args['host-out']) write(join(args['host-out'], 'bridgeOps.generated.ts'), emitHost(ops));
if (args['docs-out']) write(args['docs-out'], emitDocs(ops));

if (warnings.length) {
  console.warn(`\n${warnings.length} warning(s):`);
  for (const w of [...new Set(warnings)]) console.warn(`  ! ${w}`);
}
console.log('done.');
